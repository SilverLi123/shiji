'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const library = require('../static/library');
const covers = require('../static/shiji-v2');
const board = require('../static/board-model');
const { resources, id, attachmentId } = JSON.parse(fs.readFileSync(0, 'utf8'));
const row = resources.find(r => r.id === id);
assert.ok(row);
assert.equal(library.matches(row, { search: 'V3 精确', tags: ['New, exact'], category: '开发工具' }), true);
assert.equal(library.matches(row, { tags: ['New', 'exact'] }), false);
assert.equal(library.matches(row, { search: 'no-match-query' }), false);
assert.equal(library.matches(row, { category: '音频' }), false);
assert.equal(library.matches(row, { favorite: true }), true);
assert.equal(board.cover(row), '/api/files/' + attachmentId);
const before = JSON.stringify(row), markup = covers.coverMarkup(row);
assert.ok(markup.includes('V3 精确'));
assert.ok(markup.includes('Swift'));
assert.ok(markup.includes('cover-tool'));
assert.equal(JSON.stringify(row), before);
const prompt = resources.find(r => r.kind === 'prompt');
assert.ok(covers.coverMarkup(prompt).includes('Exact &lt;prompt&gt;'));
console.log('PASS: HTTP records -> search/filter/exact tags, real cover priority, escaped content and immutable template identity');
